# -*- coding: utf-8 -*-
"""Independent page-image OCR corroboration for cells whose evidence was the
source PDF text layer.

Input : sources/textlayer_backfill.md  (generated by tools/tlbackfill.py)
Method: render the cited source PDF pages at 300 dpi, OCR them with RapidOCR,
        then look for every numeric token of the artifact cell in that OCR text.
Output: sources/ocr_backfill.md        (per-cell evidence, quoted OCR line)
        build/ocr_matches.tsv          (label, row, col, pdf_page, tokens, hit, verdict)

The OCR text of each page is cached under build/_ocr/up_<pdf>.txt so a rerun
does not pay the OCR cost again; the tool itself is the reproducible recipe.

Usage: python tools/ocr_backfill.py
"""
import io
import os
import re
import sys
import time

import pymupdf
from rapidocr_onnxruntime import RapidOCR

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN_MD = os.path.join(ROOT, 'sources', 'textlayer_backfill.md')
OUT_MD = os.path.join(ROOT, 'sources', 'ocr_backfill.md')
CACHE = os.path.join(ROOT, 'build', '_ocr')
MATCHES = os.path.join(ROOT, 'build', 'ocr_matches.tsv')

# up volume: book page = PDF page - 19
SRC = {
    'up': (r'C:\Users\53150\.dsh\attachments\v1\files\9f'
           r'\9f97a9804d81e20c13ef2a42d2ed7e9964fe1bca5f3c3dba338d1b6d6f8159f7'
           r'\现代催化研究方法新编 上 (辛勤，罗孟飞，徐杰 主编) (z-library.sk, 1lib.sk, z-lib.sk).pdf'),
    'down': (r'C:\Users\53150\.dsh\attachments\v1\files\a1'
             r'\a1b8bc6b3dc73c6fdec8445f6d111b9113f551727f34eb01b16150141558f62c'
             r'\现代催化研究方法新编(下册) (辛勤, 罗孟飞, 徐杰) (z-library.sk, 1lib.sk, z-lib.sk).pdf'),
}

# a few rows cite a section range whose numbers sit just outside the summary
# range; scan the neighbouring pages before declaring a miss
EXTRA = {'tab:raman-bands-c': list(range(383, 391))}

DASHES = dict.fromkeys(map(ord, '\u2010\u2011\u2012\u2013\u2014\u2015\u2212\uff0d'), '-')
FW = {ord(f): ord(t) for f, t in zip('０１２３４５６７８９．％', '0123456789.%')}


def norm(s):
    s = s.translate(DASHES).translate(FW)
    s = s.replace('～', '~').replace('∼', '~').replace('—', '-')
    s = re.sub(r'\s+', '', s)
    return s


CJK_STOP = ('源书', '文字层', '命中', '文字', '说明', '同上', '见下', '核对', '本条',
            '一节', '后段', '正文', '图片', '图像', '页码', '判定', '依据', '同页',
            '判据', '怎么做', '支持', '结果', '实例', '反例', '本书', '支持「中间体」',
            '文字层命中', '支持「中间体」的结果')


def cjk_tokens(text, limit=4):
    """Distinctive Chinese terms (>=3 chars) for qualitative cells."""
    terms = []
    for run in re.findall(r'[\u4e00-\u9fff]{3,}', text):
        if run in CJK_STOP or len(run) < 3:
            continue
        if run in terms:
            continue
        terms.append(run)
        if len(terms) >= limit:
            break
    return terms


def num_tokens(text):
    """Numeric tokens worth checking: 3.5, 0.05, 400, 5.46 (single digits dropped)."""
    toks = re.findall(r'\d+(?:\.\d+)?', norm(text))
    keep = []
    for t in toks:
        if len(t.replace('.', '')) < 2:   # a lone digit is not evidence
            continue
        if t not in keep:
            keep.append(t)
    return keep


def pdf_pages(cell_page_text):
    """'书内 p.498—501 / PDF 517—520' -> [517, 518, 519, 520]"""
    m = re.search(r'PDF\s*p?\.?\s*(\d+)\s*[—\-–~]\s*(\d+)', cell_page_text)
    if m:
        a, b = int(m.group(1)), int(m.group(2))
        return list(range(a, b + 1))
    m = re.search(r'PDF\s*p?\.?\s*(\d+)', cell_page_text)
    return [int(m.group(1))] if m else []


def ocr_page(vol, pdf_page, ocr):
    os.makedirs(CACHE, exist_ok=True)
    cache = os.path.join(CACHE, '%s_%d.txt' % (vol, pdf_page))
    if os.path.exists(cache):
        return io.open(cache, encoding='utf-8').read()
    doc = pymupdf.open(SRC[vol])
    png = os.path.join(CACHE, '%s_%d.png' % (vol, pdf_page))
    doc[pdf_page - 1].get_pixmap(dpi=300).save(png)
    t0 = time.time()
    res, _ = ocr(png)
    lines = []
    for box, text, score in (res or []):
        y = int(min(float(p[1]) for p in box))
        lines.append((y, text))
    lines.sort()
    out = '\n'.join('%s' % t for _, t in lines)
    io.open(cache, 'w', encoding='utf-8', newline='\n').write(out)
    print('ocr %s p.%d lines=%d %.1fs' % (vol, pdf_page, len(lines), time.time() - t0))
    return out


def parse_summary():
    """table -> [pdf pages] from the 汇总 table of textlayer_backfill.md."""
    out = {}
    txt = io.open(IN_MD, encoding='utf-8').read().split('\n')
    for line in txt:
        if not line.startswith('| `tab:'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) < 3:
            continue
        label = cells[0].strip('`')
        pages = pdf_pages(cells[2])
        if pages:
            out[label] = pages
    return out


def parse_cells():
    """[(table, row, col, content, pages_text, verdict, note)]"""
    txt = io.open(IN_MD, encoding='utf-8').read().split('\n')
    table = None
    rows = []
    for line in txt:
        if line.startswith('### '):
            table = line[4:].strip().strip('`')
            continue
        if not line.startswith('|') or table is None:
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) < 6 or cells[0] in ('行', '---') or set(cells[0]) <= set('-: '):
            continue
        rows.append((table, cells[0], cells[1], cells[2], cells[3], cells[4], cells[5]))
    return rows


def main():
    rows = parse_cells()
    if not rows:
        print('no cells parsed')
        return 1
    print('cells', len(rows))

    ocr = RapidOCR()
    cache = {}
    summary = parse_summary()
    results = []
    for table, row, col, content, pages_text, verdict, note in rows:
        pages = pdf_pages(pages_text) or summary.get(table, [])
        # numbers live in the note column for most rows; strip page and section
        # citations first, otherwise they pollute the token list
        text_for_tokens = content + ' ' + note
        text_for_tokens = re.sub(
            r'(?:pp?\.|PDF)\s*\d+(?:\s*[/、,，]\s*\d+)*(?:\s*[—\-–~]\s*\d+)?', ' ',
            text_for_tokens)
        text_for_tokens = re.sub(r'§\s*\d+(?:\.\d+)*', ' ', text_for_tokens)
        text_for_tokens = re.sub(r'\b\d+\s*[—\-–~]\s*\d+\b', ' ', text_for_tokens)
        pset = set(pages)
        toks = [t for t in num_tokens(text_for_tokens)
                if not (t.isdigit() and int(t) in pset)]
        terms = [] if toks else cjk_tokens(note)
        hits, miss, evidence = [], [], []
        scanned = list(pages) + [p for p in EXTRA.get(table, []) if p not in pages]
        for p in scanned:
            if p not in cache:
                cache[p] = ocr_page('up', p, ocr)
            hay = norm(cache[p])
            for t in toks:
                if t not in hits and t in hay:
                    hits.append(t)
                    for ln in cache[p].split('\n'):
                        if t in norm(ln):
                            evidence.append('p.%d: %s' % (p, ln.strip()[:90]))
                            break
            for t in terms:
                if t not in hits and norm(t) in hay:
                    hits.append(t)
                    for ln in cache[p].split('\n'):
                        if norm(t) in norm(ln):
                            evidence.append('p.%d: %s' % (p, ln.strip()[:90]))
                            break
        want = toks + terms
        miss = [t for t in want if t not in hits]
        unit = '数值' if toks else '关键词'
        if not want:
            v = '无判据'
        elif not miss:
            v = 'OCR 命中全部' + unit
        elif hits:
            v = 'OCR 部分命中'
        else:
            v = 'OCR 未见'
        results.append((table, row, col, ','.join(map(str, scanned)) and
                        ','.join(map(str, pages)),
                        ' '.join(toks), ' '.join(hits), ' '.join(miss), v, evidence,
                        content, ' '.join(terms)))

    # ---- report -------------------------------------------------------
    from collections import OrderedDict
    by_table = OrderedDict()
    for r in results:
        by_table.setdefault(r[0], []).append(r)

    ok = sum(1 for r in results if r[7] == 'OCR 命中全部数值')
    num_fail = sum(1 for r in results if r[4] and r[7] != 'OCR 命中全部数值')
    qual = sum(1 for r in results if not r[4])

    out = ['# 表格单元格的页面图像 OCR 复核（独立于源文字层）', '',
           '本文件由 `tools/ocr_backfill.py` 生成：对 `sources/textlayer_backfill.md` 中'
           '「证据为源文字层」的 46 个单元格，把所引源页以 300 dpi 渲成图像、用 RapidOCR 独立识别，'
           '再逐格在该页 OCR 文本里找回单元格的每一个数值 token。', '',
           '这是**独立于 PDF 内嵌文字层**的第二条机器证据通道：文字层（出版方 OCR）与本轮'
           '重新渲染后再识别的 OCR 由不同流程产生；同一组数值在两条通道同时出现，'
           '证据强度高于单一文字层。', '',
           '**适用范围**：本方法只能判「数值」，不能判定性表述——源书原句与本改编本措辞不同，'
           '关键词比对不构成证据，故定性格不在此列，仍需人工读图。'
           'OCR 也可能认错上下标与小数点，凡未全部命中的格一律保留原判定。', '',
           '| 结论 | 格数 |', '|---|---|',
           '| 数值格：OCR 命中全部数值 | %d |' % ok,
           '| 数值格：部分/未命中（待人工） | %d |' % (num_fail),
           '| 定性格：无数值可判（仍需人工读图） | %d |' % qual,
           '| **合计** | **%d** |' % len(results), '']

    for table, items in by_table.items():
        out += ['## `%s`' % table, '',
                '| 行 | 列 | 改编本内容 | 源 PDF 页 | 数值 token | OCR 命中 | 结论 |',
                '|---|---|---|---|---|---|---|']
        for item in items:
            (tbl, row, col, pages, toks, hits, miss, v, ev, content, terms) = item
            out.append('| %s | %s | %s | %s | %s | %s | %s |' %
                       (row, col, content, pages,
                        toks or (('词: ' + terms) if terms else '—'),
                        hits or '—', v))
        out += ['', '### 证据行摘录', '']
        for item in items:
            (tbl, row, col, pages, toks, hits, miss, v, ev, content, terms) = item
            if not ev:
                continue
            out.append('- **%s / 第 %s 行 / %s 列**' % (tbl, row, col))
            for line in ev[:4]:
                out.append('  - `%s`' % line.replace('|', '\\|'))
        out.append('')

    io.open(OUT_MD, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')

    with io.open(MATCHES, 'w', encoding='utf-8', newline='\n') as f:
        f.write('label\trow\tcol\tpdf_pages\ttokens\thits\tmiss\tverdict\n')
        for (tbl, row, col, pages, toks, hits, miss, v, ev, content, terms) in results:
            f.write('\t'.join([tbl, row, col, pages, toks, hits, miss, v]) + '\n')

    print('wrote', OUT_MD)
    print('num_ok=%d num_fail=%d qualitative=%d' % (ok, num_fail, qual))
    return 0


if __name__ == '__main__':
    sys.exit(main())
