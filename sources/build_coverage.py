_CJK = '\u3400-\u9fff'


def norm_ws(text):
    text = re.sub(r'[\s\u3000]+', ' ', text).strip()
    prev = None
    while prev != text:
        prev = text
        # 去掉 CJK 与拉丁字母/数字之间的单空格
        text = re.sub(r'(?<=[0-9A-Za-z\)\]])\s(?=[%s])' % _CJK, '', text)
        text = re.sub(r'(?<=[%s])\s(?=[0-9A-Za-z\(])' % _CJK, '', text)
    return text


