def note_text(state, vol, lineno, extra):
    if state == 'ok':
        return ''
    parts = ['原始OCR：' + raw_of(vol, lineno)]
    if extra:
        parts.append(extra)
    return '；'.join(parts)


def build_rows():
    by_ch = OrderedDict()
    for item in SECTIONS:
        by_ch.setdefault(item[1], []).append(item)

    rows = []
    for (ch, vol, title, page, lineno, state, extra) in CHAPTERS:
        rows.append(OrderedDict([
            ('id', '%s-C%d' % ('UP' if vol == 'S1' else 'DN', ch)),
            ('vol', vol),
            ('ch', ch),
            ('ch_title', title),
            ('level', 1),
            ('sec', ''),
            ('title', title),
            ('book_page', page),
            ('ocr_state', state),
            ('note', note_text(state, vol, lineno, extra)),
        ]))
        for (sline, sch, level, sec, stitle, spage, sstate, sextra) in by_ch.get(ch, []):
            rows.append(OrderedDict([
                ('id', '%s-%s' % ('UP' if vol == 'S1' else 'DN', sec)),
                ('vol', vol),
                ('ch', sch),
                ('ch_title', title),
                ('level', level),
                ('sec', sec),
                ('title', norm_ws(stitle)),
                ('book_page', spage),
                ('ocr_state', sstate),
                ('note', note_text(sstate, vol, sline, sextra)),
            ]))
    return rows


